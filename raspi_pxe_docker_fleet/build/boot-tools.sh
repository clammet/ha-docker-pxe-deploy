#!/usr/bin/env bash
set -euo pipefail
cd /work
mkdir -p .cache out/bin
download() {
  local name=$1 url=$2 digest=$3
  if [[ ! -f .cache/$name ]]; then
    curl -fL --retry 3 --connect-timeout 20 --max-time 600 "$url" -o ".cache/$name.part"
    mv ".cache/$name.part" ".cache/$name"
  fi
  echo "$digest  .cache/$name" | sha256sum --check
}
download u-boot-2026.07.tar.bz2 https://ftp.denx.de/pub/u-boot/u-boot-2026.07.tar.bz2 \
  78e8bfc382fe388f9b55aa1daf8c563522a037779b5d4c349d1415e381f1243e
download busybox-1.37.0.tar.bz2 https://busybox.net/downloads/busybox-1.37.0.tar.bz2 \
  3311dff32e746499f4df0d5df04d7eb396382d7e108bb9250e7b519b837043a4
build_root=$(mktemp -d)
trap 'rm -rf "$build_root"' EXIT
tar -xjf .cache/u-boot-2026.07.tar.bz2 -C "$build_root"
tar -xjf .cache/busybox-1.37.0.tar.bz2 -C "$build_root"
uboot_source="$build_root/u-boot-2026.07"
busybox_source="$build_root/busybox-1.37.0"
export SOURCE_DATE_EPOCH=1783382400 KBUILD_BUILD_USER=ha-pxe KBUILD_BUILD_HOST=builder
models=(${1:-all})
[[ ${models[0]} != all ]] || models=(pi2 pi3 pi3plus)
[[ ${BUSYBOX_ONLY:-0} != 1 ]] || models=(pi2 pi3)
for model in "${models[@]}"; do
  case "$model" in
    pi2) config=rpi_2_defconfig; cross=arm-linux-gnueabihf- ;;
    pi3) config=rpi_3_defconfig; cross=aarch64-linux-gnu- ;;
    pi3plus) config=rpi_3_b_plus_defconfig; cross=aarch64-linux-gnu- ;;
    *) exit 2 ;;
  esac
  dest="$PWD/out/bin/$model"
  mkdir -p "$dest"
  if [[ ${BUSYBOX_ONLY:-0} != 1 ]]; then
    ub="$build_root/build-uboot-$model"
    make -C "$uboot_source" O="$ub" CROSS_COMPILE="$cross" "$config"
    # No persistent environment, boot counters, or implicit fallback into a shell.
    "$uboot_source/scripts/config" --file "$ub/.config" \
      -d ENV_IS_IN_FAT -d ENV_IS_IN_MMC -e ENV_IS_NOWHERE \
      -e USE_BOOTCOMMAND --set-str BOOTCOMMAND \
      'while true; do if fatload mmc 0:1 ${scriptaddr} boot.scr; then source ${scriptaddr}; fi; sleep 10; done' \
      --set-val BOOTDELAY -2 -e CMD_HASH -e HASH -e SHA256 -e SHA256SUM_VERIFY \
      -e CMD_IMPORTENV -e CMD_MEMORY -e CMD_SETEXPR -e CMD_SLEEP -e CMD_IMI -e CMD_SOURCE
    make -C "$uboot_source" O="$ub" CROSS_COMPILE="$cross" olddefconfig
    make -C "$uboot_source" O="$ub" CROSS_COMPILE="$cross" -j"${JOBS:-4}"
    cp "$ub/u-boot.bin" "$dest/"
    cp "$ub/.config" "$dest/uboot.config"
  fi
  bb="$build_root/build-busybox-$model"
  mkdir -p "$bb"
  make -C "$busybox_source" O="$bb" CROSS_COMPILE="$cross" defconfig > /dev/null
  # Large modprobe reads modules.dep generated by prepare.py; static avoids target libc dependencies.
  "$uboot_source/scripts/config" --file "$bb/.config" \
    -e STATIC -d MODPROBE_SMALL -e MODPROBE -e INSMOD -e FEATURE_INSMOD_TRY_MMAP \
    -d TC -d SHA1_HWACCEL -d SHA256_HWACCEL
  make -C "$busybox_source" O="$bb" CROSS_COMPILE="$cross" oldconfig < /dev/null > /dev/null
  make -C "$busybox_source" O="$bb" CROSS_COMPILE="$cross" -j"${JOBS:-4}" > "$dest/busybox-build.log" 2>&1 || {
    tail -60 "$dest/busybox-build.log"; exit 1;
  }
  cp "$bb/busybox" "$dest/"
  cp "$bb/.config" "$dest/busybox.config"
  if [[ ${BUSYBOX_ONLY:-0} != 1 ]]; then
    (cd "$dest" && sha256sum u-boot.bin busybox > SHA256SUMS)
  fi
done
